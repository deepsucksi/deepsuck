"""#219 三审：「姓」作锚词、锚词隔破折号 / 引号、句号隔开的逐字解释（复审 issuecomment-6282965985 的复现句 + 负责人补充规则）。"""
import pytest

from voice.persona import speakable

CASES = [
    # 必改 1：「姓」作锚词，「姓」一并换掉；主语后直接跟「姓」时改成「是」
    ("收款人姓**明", "收款人那个名字"),
    ("他姓**明", "他是那个名字"),
    ("对方姓*名明", "对方是那个名字"),
    # 必改 1：锚词和星号之间隔破折号、引号
    ("户名 —— **明", "户名 —— 那个名字"),
    ("收款人“**”", "收款人“那个名字”"),
    # 停字照旧
    ("收款人姓**的卡", "收款人那个名字的卡"),
    ("他姓**是吧", "他是那个名字是吧"),
    # 必改 2：句号 / 逗号隔开的逐字解释，前面的单字也打码
    ("伟。伟大的伟", "那个名字"),
    ("伟，伟大的伟", "那个名字"),
    # 已有行为不变（「他姓张**」按四审改）
    ("收款人姓* *", "收款人那个名字"),
    ("他姓张**", "他是那个名字"),
    # 四审（负责人定）：「姓」后接「的」时，人称和「姓」一起去掉；#136 老规则作废，「他姓张**」也念「他是那个名字」
    ("我姓**的卡", "那个名字的卡"),
    ("他姓张**的卡", "那个名字的卡"),
    ("对方姓**的账户", "那个名字的账户"),
    ("她姓张**", "她是那个名字"),
    ("他姓欧阳**", "他是那个名字"),
    ("姓张**", "那个名字"),
    ("户名，*明", "户名，那个名字"),
]


@pytest.mark.parametrize("text,want", CASES)
def test_surname_anchor(text, want):
    out = speakable(text, calm_tts=False)
    assert out == want
    assert "明" not in out and "伟" not in out and "那个号" not in out
